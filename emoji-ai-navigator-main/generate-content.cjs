function extractField(block, field) {
  let m = block.match(new RegExp(`${field}:\\s*'([^']*)'`));
  if (m) return m[1];
  m = block.match(new RegExp(`${field}:\\s*"([^"]*)"`));
  if (m) return m[1];
  return '';
}

function extractUrl(block) {
  const m = block.match(/url:\s*'([^']*)'/);
  if (m) return m[1];
  const m2 = block.match(/url:\s*"([^"]*)"/);
  if (m2) return m2[1];
  return '';
}

function extractTags(block) {
  const m = block.match(/tags:\s*\[([\s\S]*?)\]/);
  if (!m) return [];
  return m[1].match(/["']([^"']+)["']/g)?.map(s => s.replace(/["']/g, '')) || [];
}

function getDomain(url) {
  try { return new URL(url).hostname.replace('www.', ''); } catch { return ''; }
}

function hashCode(str) {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = ((hash << 5) - hash) + str.charCodeAt(i);
    hash |= 0;
  }
  return hash;
}

