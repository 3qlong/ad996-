// Generate usageTips
function genUsageTips(name, desc, category, tags) {
  const meta = categoryMeta[category] || categoryMeta['AI办公'];
  const scenarios = Object.keys(meta.scenarioTips);
  const tipFns = meta.scenarioTips;

  // Select 4-5 scenarios deterministically based on tool name hash
  const h = Math.abs(hashCode(name));
  const count = 4 + (h % 2);

  // Shuffle scenarios deterministically
  const indexed = scenarios.map((s, i) => ({ s, sort: hashCode(name + s + i) }));
  indexed.sort((a, b) => a.sort - b.sort);
  const selected = indexed.slice(0, count).map(x => x.s);

  let tips = `如何使用${name}\n\n${name}可以在多种场景下为用户提供智能化支持，以下是几个核心应用方式：\n\n`;

  selected.forEach((sc, i) => {
    tips += `${i + 1}. ${tipFns[sc](name)}\n\n`;
  });

  tips += `使用小贴士：\n\n• 首次使用建议先浏览${name}的功能引导或帮助文档，快速了解各模块的能力边界\n• 尝试不同的参数设置和描述方式，找到最适合自己需求的使用方法\n• 善用${name}的历史记录和收藏功能，方便后续查找和复用优质成果\n• 关注${name}的版本更新动态，及时体验新功能和性能改进`;

  return tips;
}

function escapeForSingleQuote(str) {
  return str.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
}

// Parse tool blocks
const blockRegex = /\{\s*\n\s*id:\s*(\d+),/g;
let blockMatch;
const blockStarts = [];

while ((blockMatch = blockRegex.exec(content)) !== null) {
  blockStarts.push({ index: blockMatch.index, id: parseInt(blockMatch[1]) });
}

const toolBlocks = [];
for (let i = 0; i < blockStarts.length; i++) {
  const start = blockStarts[i].index;
  const end = i < blockStarts.length - 1 ? blockStarts[i + 1].index : content.lastIndexOf('];');
  const block = content.substring(start, end);
  toolBlocks.push({
    id: blockStarts[i].id, start, end, block,
    name: extractField(block, 'name'),
    description: extractField(block, 'description'),
    category: extractField(block, 'category'),
    url: extractUrl(block),
    tags: extractTags(block),
  });
}

console.log(`Found ${toolBlocks.length} tools to process`);

let processed = 0, errors = 0;
let newContent = content;

for (let i = toolBlocks.length - 1; i >= 0; i--) {
  const t = toolBlocks[i];
  if (!t.name || !t.category) { errors++; continue; }

  const newProductIntro = genProductIntro(t.name, t.description, t.category, t.tags, t.url);
  const newUsageTips = genUsageTips(t.name, t.description, t.category, t.tags);

  const block = newContent.substring(t.start, t.end);

  let updatedBlock = block.replace(
    /productIntro:\s*'[^']*'/,
    `productIntro: '${escapeForSingleQuote(newProductIntro)}'`
  );
  updatedBlock = updatedBlock.replace(
    /usageTips:\s*'[^']*'/,
    `usageTips: '${escapeForSingleQuote(newUsageTips)}'`
  );

  const newLongDesc = `${t.name}是${categoryMeta[t.category]?.field || t.category}领域的专业工具，${t.description}。为${(categoryMeta[t.category]?.users || ['用户']).slice(0, 2).join('、')}等提供高效的AI解决方案。`;
  updatedBlock = updatedBlock.replace(
    /longDescription:\s*'[^']*'/,
    `longDescription: '${escapeForSingleQuote(newLongDesc)}'`
  );

  newContent = newContent.substring(0, t.start) + updatedBlock + newContent.substring(t.end);
  processed++;
  if (processed % 200 === 0) console.log(`Processed ${processed}/${toolBlocks.length}...`);
}

console.log(`Processed: ${processed}, Errors: ${errors}`);
fs.writeFileSync(filePath, newContent, 'utf8');
console.log('Done! File updated successfully.');
